// ev001Tampered applies two same-length byte replacements so file size is
// unchanged and aligned block hashing localizes the edit precisely.
func ev001Tampered(orig []byte) []byte {
	b := append([]byte(nil), orig...)
	s := string(b)
	s = strings.Replace(s, "02:40 巡更系统报警", "01:50 巡更系统报警", 1)
	s = strings.Replace(s, "3号库西侧巡更点", "5号库西侧巡更点", 1)
	return []byte(s)
}

