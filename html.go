// WriteHTMLReport writes a self-contained HTML report with an inline SVG
// chromaticity diagram and the same tables as the text demo.
func WriteHTMLReport(path string, r *DemoReport) error {
	var b strings.Builder
	b.WriteString(`<!doctype html><html lang="zh-CN"><head><meta charset="utf-8">`)
	b.WriteString(`<meta name="viewport" content="width=device-width, initial-scale=1">`)
	b.WriteString(`<title>CIE 2°↔10° observer empirical mapping</title><style>` + reportCSS + `</style></head><body>`)

	b.WriteString(`<header><h1>CIE 1931 2° ↔ CIE 1964 10° 标准观察者：实验式映射</h1>`)
	b.WriteString(`<p class="disclaimer">⚠ ` + html.EscapeString(r.Disclaimer) + `</p></header>`)

	b.WriteString(`<section><h2>Profile / provenance</h2>` + certaintyHTML(r.Profile) + `</section>`)

	b.WriteString(`<section><h2>xy 色度图：2° → 10° 位移</h2>`)
	b.WriteString(svgChromaticity(r))
	b.WriteString(`<p class="note">实线马蹄形为 1931 2° 光谱轨迹，虚线为 1964 10° 轨迹；箭头从 2° 坐标指向 10°（光谱样本为直接积分真值，色板为经验映射估计值）。</p>`)
	b.WriteString(`</section>`)

	b.WriteString(`<section><h2>A. 光谱样本（两种观察者均由光谱直接积分）</h2>`)
	b.WriteString(spectralTableHTML(r.Spectral))
	b.WriteString(`</section>`)

	b.WriteString(`<section><h2>B. sRGB 色板（10° 为经验映射估计）</h2>`)
	b.WriteString(swatchTableHTML(r.Swatches))
	b.WriteString(`</section>`)

	b.WriteString(`<section><h2>Empirical map</h2>`)
	b.WriteString(`<h3>D65 · 2° → 10°</h3>` + matrixHTML(r.MapD65))
	b.WriteString(`<h3>D65 · 10° → 2°（独立拟合的反向最小二乘）</h3>` + matrixHTML(r.MapD65Reverse))
	b.WriteString(`<details><summary>D50 矩阵</summary>`)
	b.WriteString(`<h3>D50 · 2° → 10°</h3>` + matrixHTML(r.MapD50))
	b.WriteString(`<h3>D50 · 10° → 2°</h3>` + matrixHTML(r.MapD50Reverse))
	b.WriteString(`</details>`)
	b.WriteString(`</section>`)

	b.WriteString(`<footer>Generated by <code>observermap</code> · 数据：内嵌 CIE 1931/1964 CMF 与 CIE D50/D65 SPD（5 nm，380–780 nm）</footer>`)
	b.WriteString(`</body></html>`)

	return os.WriteFile(path, []byte(b.String()), 0o644)
}

