func certaintyHTML(c Certainty) string {
	cls := "ok"
	status := "provenance OK — empirical approximation still applies"
	if c.Uncertain {
		cls = "uncertain"
		status = "UNCERTAIN"
	}
	var b strings.Builder
	fmt.Fprintf(&b, `<p class="%s"><strong>%s</strong></p>`, cls, status)
	fmt.Fprintf(&b, `<p>profile: <code>%s</code><br>`, orDash(c.ProfilePath))
	fmt.Fprintf(&b, "white point: <strong>%s</strong> (supported=%v)<br>", c.WhitePoint, c.WhiteSupported)
	fmt.Fprintf(&b, "observer recorded by ICC profile: <strong>%v</strong></p>", c.ObserverRecorded)
	if len(c.Reasons) > 0 {
		b.WriteString("<ul>")
		for _, rs := range c.Reasons {
			fmt.Fprintf(&b, "<li>%s</li>", html.EscapeString(rs))
		}
		b.WriteString("</ul>")
	}
	return b.String()
}

func orDash(s string) string {
	if s == "" {
		return "(none supplied)"
	}
	return html.EscapeString(s)
}

func spectralTableHTML(rows []ColorRow) string {
	var b strings.Builder
	b.WriteString(`<table><thead><tr><th>Sample</th><th>x₂</th><th>y₂</th><th>x₁₀ direct</th><th>y₁₀ direct</th><th>Δxy</th><th>ΔE00</th><th>map residual ΔE00</th></tr></thead><tbody>`)
	for _, r := range rows {
		fmt.Fprintf(&b, `<tr><td>%s</td><td>%.4f</td><td>%.4f</td><td>%.4f</td><td>%.4f</td><td>%.5f</td><td>%.2f</td><td>%.2f</td></tr>`,
			html.EscapeString(r.Name), r.X2, r.Y2, r.X10, r.Y10, r.DeltaXY, r.DeltaE00, r.MapResidualDE00)
	}
	b.WriteString(`</tbody></table>`)
	return b.String()
}

func swatchTableHTML(rows []ColorRow) string {
	var b strings.Builder
	b.WriteString(`<table><thead><tr><th>Swatch</th><th>hex</th><th>x₂</th><th>y₂</th><th>x₁₀ est</th><th>y₁₀ est</th><th>Δxy est</th><th>ΔE00 est</th><th>Status</th></tr></thead><tbody>`)
	for _, r := range rows {
		status := `<span class="tag-a">approximate</span>`
		if r.Uncertain {
			status = `<span class="tag-u">UNCERTAIN</span>`
		}
		fmt.Fprintf(&b, `<tr><td><span class="swatch" style="background:%s"></span>%s</td><td>%s</td><td>%.4f</td><td>%.4f</td><td>%.4f</td><td>%.4f</td><td>%.5f</td><td>%.2f</td><td>%s</td></tr>`,
			r.Hex, html.EscapeString(r.Name), r.Hex, r.X2, r.Y2, r.X10, r.Y10, r.DeltaXY, r.DeltaE00, status)
	}
	b.WriteString(`</tbody></table>`)
	return b.String()
}

func matrixHTML(m EmpiricalMap) string {
	var b strings.Builder
	b.WriteString(`<p><code>` + html.EscapeString(m.Method) + `</code></p><pre>`)
	for i := 0; i < 3; i++ {
		fmt.Fprintf(&b, "[%9.5f %9.5f %9.5f]\n", m.Matrix[i][0], m.Matrix[i][1], m.Matrix[i][2])
	}
	q := m.Quality
	fmt.Fprintf(&b, "</pre><p class='note'>held-out %d samples: median ΔE00=%.2f, p95=%.2f, max=%.2f</p>",
		m.TestSamples, q.MedianDE00, q.P95DE00, q.MaxDE00)
	return b.String()
}

