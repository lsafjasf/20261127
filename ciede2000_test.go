package colorcompare

import (
	"math"
	"testing"
)

func TestDeltaE2000SharmaReferenceVectors(t *testing.T) {
	tests := []struct {
		name     string
		lab1     Lab
		lab2     Lab
		expected float64
	}{
		{"01", Lab{50, 2.6772, -79.7751}, Lab{50, 0, -82.7485}, 2.0425},
		{"02", Lab{50, 3.1571, -77.2803}, Lab{50, 0, -82.7485}, 2.8615},
		{"03", Lab{50, 2.8361, -74.0200}, Lab{50, 0, -82.7485}, 3.4412},
		{"04", Lab{50, -1.3802, -84.2814}, Lab{50, 0, -82.7485}, 1.0000},
		{"05", Lab{50, -1.1848, -84.8006}, Lab{50, 0, -82.7485}, 1.0000},
		{"06", Lab{50, -0.9009, -85.5211}, Lab{50, 0, -82.7485}, 1.0000},
		{"07", Lab{50, 0, 0}, Lab{50, -1, 2}, 2.3669},
		{"08", Lab{50, -1, 2}, Lab{50, 0, 0}, 2.3669},
		{"09", Lab{50, 2.49, -0.001}, Lab{50, -2.49, 0.0009}, 7.1792},
		{"10", Lab{50, 2.49, -0.001}, Lab{50, -2.49, 0.0010}, 7.1792},
		{"11", Lab{50, 2.49, -0.001}, Lab{50, -2.49, 0.0011}, 7.2195},
		{"12", Lab{50, 2.49, -0.001}, Lab{50, -2.49, 0.0012}, 7.2195},
		{"13", Lab{50, -0.001, 2.49}, Lab{50, 0.0009, -2.49}, 4.8045},
		{"14", Lab{50, -0.001, 2.49}, Lab{50, 0.0010, -2.49}, 4.8045},
		{"15", Lab{50, -0.001, 2.49}, Lab{50, 0.0011, -2.49}, 4.7461},
		{"16", Lab{50, 2.5, 0}, Lab{50, 0, -2.5}, 4.3065},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got := DeltaE2000(tt.lab1, tt.lab2)
			if math.Abs(got-tt.expected) > 1e-4 {
				t.Fatalf("DeltaE2000() = %.6f, want %.4f", got, tt.expected)
			}
			reversed := DeltaE2000(tt.lab2, tt.lab1)
			if math.Abs(got-reversed) > 1e-12 {
				t.Fatalf("DeltaE2000 is asymmetric: %.12f vs %.12f", got, reversed)
			}
		})
	}
}

